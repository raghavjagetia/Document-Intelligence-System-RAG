"""
Seed SAMPLE answer feedback (thumbs up / down) so the Dashboard's "Answer feedback" chart is not empty in a demo.

These ratings are DEMO DATA generated by this script, not opinions of real users - never report them as user
feedback. They follow answer quality so the chart is plausible: confident, well-supported answers are mostly rated
helpful, refusals and low-confidence answers more often not helpful, with a little seeded randomness.

To give every answer style data, the demo account also asks a set of benchmark questions in the "Detailed answer"
and "Exact quote" styles. This runs with the LLM switched off (no API quota is used), so detailed answers are the
offline extractive ones.

Usage:
  python scripts/seed_feedback.py            # rate unrated answers; ask style samples if none exist yet
  python scripts/seed_feedback.py --share 0.8
Safe to run again: answers that already have a rating are left alone.
"""
import argparse
import json
import os
import random
import sys
from pathlib import Path

os.environ["LLM_PROVIDER"] = "none"  # offline answers only: no API quota is spent on demo data
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.config import Config  # noqa: E402

STYLE_SAMPLES = 12  # questions asked per extra style


def ask_style_samples(s, user_id: str, rng: random.Random, per_style: int = STYLE_SAMPLES,
                      questions=None) -> int:
    """Ask questions in the detailed and quote styles (only once per account). `questions` defaults to answerable
    benchmark questions (the demo account owns the benchmark documents); other accounts use questions built from
    their own documents."""
    existing = s.db._one("SELECT COUNT(*) AS n FROM messages m JOIN conversations c ON c.conversation_id = "
                         "m.conversation_id WHERE c.user_id = ? AND m.answer_style IN ('detailed', 'quote')",
                         (user_id,))["n"]
    if existing:
        return 0
    if questions is None:
        cases = json.loads(Config.EVAL_DATASET.read_text(encoding="utf-8"))["test_cases"]
        questions = [c["question"] for c in cases if c.get("expected_docs") and not c.get("history")]
    if not questions:
        return 0
    asked = 0
    for style, title in (("detailed", "Detailed answers"), ("quote", "Exact quotes")):
        conv = s.db.create_conversation(user_id, title=title, domain="all")
        for q in rng.sample(questions, min(per_style, len(questions))):
            s.ask(user_id, question=q, conversation_id=conv["conversation_id"], answer_style=style)
            asked += 1
    return asked


def rate(s, share: float, rng: random.Random) -> int:
    rows = s.db._all("SELECT m.message_id, m.abstained, m.confidence_score, m.grounded, c.user_id "
                     "FROM messages m JOIN conversations c ON c.conversation_id = m.conversation_id "
                     "WHERE m.role = 'assistant' AND m.feedback IS NULL ORDER BY m.timestamp")
    rated = 0
    for r in rows:
        if rng.random() > share:
            continue  # most people do not rate every answer
        if r["abstained"]:
            p_helpful = 0.3
        else:
            p_helpful = min(0.95, 0.55 + 0.4 * (r["confidence_score"] or 0.0))
            if not r["grounded"]:
                p_helpful -= 0.25
        s.db.set_feedback(r["message_id"], r["user_id"], 1 if rng.random() < p_helpful else -1)
        rated += 1
    # every account gets some ratings, so each user's own Dashboard shows data
    for user in s.db._all("SELECT user_id FROM users"):
        left = s.db._all("SELECT m.message_id, m.abstained, m.confidence_score FROM messages m JOIN conversations c "
                         "ON c.conversation_id = m.conversation_id WHERE c.user_id = ? AND m.role = 'assistant' "
                         "AND m.feedback IS NULL", (user["user_id"],))
        have = s.db._one("SELECT COUNT(*) AS n FROM messages m JOIN conversations c ON c.conversation_id = "
                         "m.conversation_id WHERE c.user_id = ? AND m.feedback IS NOT NULL", (user["user_id"],))["n"]
        for r in left[:max(0, 3 - have)]:
            p_helpful = 0.3 if r["abstained"] else min(0.95, 0.55 + 0.4 * (r["confidence_score"] or 0.0))
            s.db.set_feedback(r["message_id"], user["user_id"], 1 if rng.random() < p_helpful else -1)
            rated += 1
    return rated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--share", type=float, default=0.75, help="share of unrated answers to rate (default 0.75)")
    args = parser.parse_args()
    from backend.services import get_services
    s = get_services()
    rng = random.Random(2026)
    demo, _ = s.auth.ensure_demo_user()
    asked = ask_style_samples(s, demo["user_id"], rng)
    # every other account: two answers per extra style, from questions about its own documents
    for user in s.db._all("SELECT user_id, username FROM users WHERE user_id != ? ORDER BY username", (demo["user_id"],)):
        n = ask_style_samples(s, user["user_id"], rng, per_style=2,
                              questions=s.pipeline.suggested_questions(user["user_id"], limit=8))
        if n:
            print(f"  {user['username']}: {n} style samples")
        asked += n
    rated = rate(s, args.share, rng)
    fb = s.db.analytics(None)["feedback"]
    print(f"\nAsked {asked} style samples, rated {rated} answers (SAMPLE DATA, not real users).")
    print(f"All accounts: {fb['helpful']} helpful, {fb['not_helpful']} not helpful, "
          f"satisfaction {fb['satisfaction']}; by style: "
          + ", ".join(f"{r['style']} {r['helpful']}/{r['not_helpful']}" for r in fb["by_style"]))


if __name__ == "__main__":
    main()
