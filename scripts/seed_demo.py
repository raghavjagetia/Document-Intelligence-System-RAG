"""
Seed the application with demo data:
  - 50 users  : the demo account + 49 sample accounts. Passwords come from .env (DEMO_PASSWORD,
                SEED_USER_PASSWORD) or are generated randomly and written to data/initial_credentials.txt
  - 50 documents (data/sample_documents) ingested into the demo account
  - 50 questions asked through the real RAG pipeline, grouped into conversations,
    with timestamps spread over the last 14 days so dashboards have history
  - 5 documents + a short chat for every other account (user01..user49), plus a few
    private documents for user01-user03 to demonstrate per-user isolation

Usage:
  python scripts/seed_demo.py            # seed (skips anything that already exists)
  python scripts/seed_demo.py --reset    # wipe app data (data/app.db, data/index, data/uploads) first
"""
import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.config import Config  # noqa: E402


def reset_data() -> None:
    for p in (Config.DB_PATH, Path(str(Config.DB_PATH) + "-wal"), Path(str(Config.DB_PATH) + "-shm")):
        p.unlink(missing_ok=True)
    for d in (Config.INDEX_DIR, Config.UPLOAD_DIR):
        if d.exists():
            shutil.rmtree(d)
    print("Cleared application data")


def ensure_sample_documents() -> list:
    manifest = Config.SAMPLE_DOCS_DIR / "manifest.json"
    if not manifest.exists():
        print("Generating sample documents…")
        subprocess.run([sys.executable, str(ROOT / "scripts" / "generate_sample_data.py")], check=True)
    return json.loads(manifest.read_text(encoding="utf-8"))


USER_DOCS_DIR = ROOT / "data" / "user_documents"
QUESTIONS_PER_USER = 4


def seed_other_users(s, duplicate_error) -> None:
    """
    Give every sample account (user01..user49) its own unique library (generated by
    scripts/generate_user_documents.py: invoice, offer letter, lab report, contract and a business
    document with per-user names, amounts and dates) plus a chat about those documents, so each
    login has different documents, insights, chats and dashboard numbers.
    """
    manifest_path = USER_DOCS_DIR / "manifest.json"
    if not manifest_path.exists():
        print("Generating per-user documents...")
        subprocess.run([sys.executable, str(ROOT / "scripts" / "generate_user_documents.py")], check=True)
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    start = datetime.now() - timedelta(days=13)
    for i, (username, info) in enumerate(sorted(manifest.items()), start=1):
        user = s.db.get_user_with_hash(username)
        if not user:
            continue
        uid = user["user_id"]
        have = {d["filename"] for d in s.db.list_documents(uid)}
        for entry in info["documents"]:
            if entry["filename"] in have:
                continue
            path = USER_DOCS_DIR / username / entry["domain"] / entry["filename"]
            with tempfile.NamedTemporaryFile(delete=False, suffix=path.suffix) as tmp:
                tmp_path = Path(tmp.name)
            shutil.copyfile(path, tmp_path)
            try:
                s.ingest_file(uid, tmp_path, entry["filename"], entry["domain"])
            except duplicate_error:
                pass
            finally:
                tmp_path.unlink(missing_ok=True)

        asked = 0
        if not s.db.list_conversations(uid):
            # rotate which questions each user asks so the chats differ in shape too
            qs = info["questions"]
            picks = [qs[(i + k * 2) % len(qs)] for k in range(QUESTIONS_PER_USER)]
            cid = None
            for j, q in enumerate(picks):
                res = s.ask(uid, question=q["question"], conversation_id=cid, domain="all")
                cid = res["conversation_id"]
                ts = (start + timedelta(hours=(i * 37 + j * 3) % (13 * 24))).isoformat(timespec="seconds")
                with s.db.conn() as c:
                    c.execute("UPDATE messages SET timestamp = ? WHERE message_id IN (?, ?)",
                              (ts, res["user_message"]["message_id"], res["assistant_message"]["message_id"]))
                    c.execute("UPDATE conversations SET updated_at = ?, created_at = MIN(created_at, ?) "
                              "WHERE conversation_id = ?", (ts, ts, cid))
                asked += 1
            s.db.rename_conversation(cid, uid, f"{info['company'].replace(' Pvt. Ltd.', '')} documents")
        print(f"  {username}: {len(s.db.list_documents(uid))} documents, {asked} questions asked")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--reset", action="store_true", help="delete existing app data before seeding")
    args = parser.parse_args()
    if args.reset:
        reset_data()

    manifest = ensure_sample_documents()
    from backend.services import DuplicateDocument, get_services
    s = get_services()
    print("System:", json.dumps(s.system_status(), indent=None))

    # ---------------------------------------------------------------- users
    demo, _ = s.auth.ensure_demo_user()
    created = 0
    sample_password = None  # one password for all sample accounts, chosen only if one has to be created
    for i in range(1, 50):
        name = f"user{i:02d}"
        if not s.db.user_exists(name, f"{name}@documind.local"):
            if sample_password is None:
                from backend.auth import initial_password
                sample_password = initial_password("sample users", "user01-user49", Config.SEED_USER_PASSWORD)
            s.auth.register(name, f"{name}@documind.local", sample_password)
            created += 1
    print(f"Users: {s.db.count_users()} total ({created} created)")

    # ---------------------------------------------------------------- documents
    ingested = 0
    for entry in manifest:
        path = Config.SAMPLE_DOCS_DIR / entry["domain"] / entry["filename"]
        with tempfile.NamedTemporaryFile(delete=False, suffix=path.suffix) as tmp:
            tmp_path = Path(tmp.name)
        shutil.copyfile(path, tmp_path)
        try:
            s.ingest_file(demo["user_id"], tmp_path, entry["filename"], entry["domain"])
            ingested += 1
            print(f"  + {entry['domain']:<10} {entry['filename']}")
        except DuplicateDocument:
            pass
        finally:
            tmp_path.unlink(missing_ok=True)
    print(f"Documents: {len(s.db.list_documents(demo['user_id']))} in demo account ({ingested} new)")

    # private documents for a few other users (isolation demo)
    private = {
        "user01": ("My_Notes.txt", "Personal Notes\n\nMy laptop asset tag is AST-2026-0457 and it is due for refresh in July 2027.\n"),
        "user02": ("Team_Contacts.txt", "Team Contacts\n\nThe on-call engineer for March is Kavya Menon, reachable at extension 4471.\n"),
        "user03": ("Project_Ideas.md", "# Project Ideas\n\nBuild a carbon-footprint tracker for office commutes with a budget of Rs. 2,50,000.\n"),
    }
    for username, (fname, text) in private.items():
        user = s.db.get_user_with_hash(username)
        with tempfile.NamedTemporaryFile("w", delete=False, suffix=Path(fname).suffix, encoding="utf-8") as tmp:
            tmp.write(text)
        try:
            s.ingest_file(user["user_id"], Path(tmp.name), fname, "general")
        except DuplicateDocument:
            pass
        finally:
            Path(tmp.name).unlink(missing_ok=True)

    cases = json.loads(Config.EVAL_DATASET.read_text(encoding="utf-8"))["test_cases"]
    seed_other_users(s, DuplicateDocument)

    # ---------------------------------------------------------------- conversations (50 questions)
    if s.db.list_conversations(demo["user_id"]):
        print("Conversations already exist - skipping chat seeding")
        return
    groups = defaultdict(list)
    for case in cases:
        groups[case["domain"] if case["domain"] in Config.DOMAINS else "general"].append(case)

    titles = {"hr": "HR policy questions", "legal": "Contract review", "healthcare": "Clinical documents",
              "finance": "Finance & invoices", "general": "General knowledge base"}
    start = datetime.now() - timedelta(days=13, hours=4)
    asked, step = 0, 0
    for domain, items in groups.items():
        # split each domain into conversations of at most 6 questions
        for part in range(0, len(items), 6):
            batch = items[part:part + 6]
            cid = None
            for case in batch:
                # follow-up questions are asked right after their antecedent in the same conversation
                for q in (case.get("history") or []) + [case["question"]]:
                    if asked >= 50:
                        break
                    res = s.ask(demo["user_id"], question=q, conversation_id=cid, domain="all")
                    cid = res["conversation_id"]
                    ts = (start + timedelta(minutes=step * 383)).isoformat(timespec="seconds")
                    step += 1
                    with s.db.conn() as c:
                        c.execute("UPDATE messages SET timestamp = ? WHERE message_id IN (?, ?)",
                                  (ts, res["user_message"]["message_id"], res["assistant_message"]["message_id"]))
                        c.execute("UPDATE conversations SET updated_at = ?, created_at = MIN(created_at, ?) "
                                  "WHERE conversation_id = ?", (ts, ts, cid))
                    asked += 1
                    m = res["assistant_message"]
                    flag = "ABSTAIN" if m["abstained"] else f"conf {m['confidence_score']:.2f}"
                    print(f"  Q{asked:02d} [{flag}] {q[:70]}")
            if cid:
                n = part // 6 + 1
                s.db.rename_conversation(cid, demo["user_id"],
                                         titles[domain] + (f" ({n})" if len(items) > 6 else ""))
    print(f"Asked {asked} questions in {len(s.db.list_conversations(demo['user_id']))} conversations")
    creds = Config.DATA_DIR / "initial_credentials.txt"
    print("\nDone." + (f" Passwords of newly created accounts are in {creds}." if creds.exists() else ""))


if __name__ == "__main__":
    main()
